#!/usr/bin/env bash
# Writes supabase/schemas/public.sql: the whole public schema as the migrations build it,
# so a reviewer reads one file instead of replaying every migration in their head.
#   scripts/db-schema.sh          rewrite the file from the local database (after `supabase db reset`)
#   scripts/db-schema.sh --check  fail when the committed file and the migrations disagree (CI)
# Uses pg_dump inside the local Supabase container, so its version always matches the server.
set -euo pipefail

FILE=supabase/schemas/public.sql
CONTAINER="supabase_db_$(grep -m1 -oP '"project_id":\s*"\K[^"]+' supabase/config.jsonc)"

dump() {
  echo "-- The whole public schema, generated by scripts/db-schema.sh from supabase/migrations."
  echo "-- Do not edit by hand: add a migration, run \`supabase db reset\`, then \`pnpm db:schema\`."
  echo "-- CI fails when this file and the migrations disagree."
  docker exec "$CONTAINER" pg_dump -U postgres -n public --schema-only --no-owner --no-comments postgres |
    sed -E '/^\\(un)?restrict /d; /^SET /d; /^SELECT pg_catalog.set_config/d; /^CREATE SCHEMA public;/d' |
    cat -s
}

if [ "${1:-}" = --check ]; then
  if ! diff -u "$FILE" <(dump); then
    echo "::error file=$FILE::The schema file does not match the migrations. Run supabase db reset, then pnpm db:schema, and commit."
    exit 1
  fi
  echo "schema file matches the migrations"
else
  dump >"$FILE"
  echo "wrote $FILE"
fi
